/**
 * Ключ дня в ЛОКАЛЬНОМ времени пользователя — "ГГГГ-ММ-ДД".
 *
 * ВАЖНО: раньше везде использовался `toISOString().slice(0,10)`, который даёт
 * дату в UTC. Для Кыргызстана (UTC+6) это значит, что с 00:00 до 06:00 по
 * местному времени приложение считало днём ВЧЕРАШНЮЮ дату: отметка Фаджра в
 * 05:00 уходила во вчерашний лог, «Сегодня» на главной было пустым, серия
 * (streak) рвалась, а ежедневный бонус выдавался не в полночь, а в 6 утра.
 *
 * Здесь берутся локальные компоненты даты — день меняется ровно в полночь по
 * часам пользователя, в любом часовом поясе.
 */
export function toDateKey(date?: Date | string): string {
  if (typeof date === "string") return date.slice(0, 10);
  const d = date ?? new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}
