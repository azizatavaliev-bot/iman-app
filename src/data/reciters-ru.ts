/** Русское имя чтеца: аккуратная форма для известных, иначе имя из API (уже русское). */
export function reciterRuName(id: number, apiName?: string): string {
  if (RECITERS_RU[id]) return RECITERS_RU[id].ru;
  return apiName || `Чтец #${id}`;
}

/** Полная справка о чтеце (или null, если нет в списке известных). */
export function reciterRuInfo(id: number): ReciterRu | null {
  return RECITERS_RU[id] || null;
}

