/** Get fact by id */
export function getFactById(id: number): IslamicFact | undefined {
  return FACTS.find((f) => f.id === id);
}

/** Stable "fact of the day" — derived from day index */
export function getFactOfTheDay(today: Date = new Date()): IslamicFact {
  const dayIdx = Math.floor(today.getTime() / (1000 * 60 * 60 * 24));
  return FACTS[dayIdx % FACTS.length];
}
