/**
 * Инфо о суре: значение названия + описание.
 * Для неописанных сур — разумный fallback (тип ниспослания + название).
 */
export function getSurahInfo(
  surahNumber: number,
  ruName: string,
  revelationType?: string,
): SurahInfo {
  const found = SURAH_INFO[surahNumber];
  if (found) return found;
  const place =
    revelationType === "Meccan" || revelationType === "meccan"
      ? "Мекканская сура"
      : revelationType === "Medinan" || revelationType === "medinan"
        ? "Мединская сура"
        : "Сура Корана";
  return {
    meaning: `«${ruName}»`,
    about: `${place}. Часть Священного Корана — читай с размышлением над смыслом и тафсиром каждого аята.`,
  };
}
