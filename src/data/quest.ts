const QUEST_KEY = "iman_quest_progress";

export interface LevelProgress {
  /** Звёзды 0-3 в зависимости от использованных жизней */
  stars: number;
  /** Сколько раз проходил */
  attempts: number;
  /** Последняя дата прохождения ISO */
  completedAt?: string;
  /** Лучший результат — правильных / всего */
  bestScore?: number;
}

export type QuestProgress = Record<string, Record<number, LevelProgress>>;

export function loadQuestProgress(): QuestProgress {
  try {
    const raw = localStorage.getItem(QUEST_KEY);
    return raw ? (JSON.parse(raw) as QuestProgress) : {};
  } catch {
    return {};
  }
}

export function saveQuestProgress(p: QuestProgress): void {
  try {
    localStorage.setItem(QUEST_KEY, JSON.stringify(p));
  } catch {
    // ignore
  }
}

export function getLevelProgress(
  worldId: string,
  levelId: number,
): LevelProgress | undefined {
  const all = loadQuestProgress();
  return all[worldId]?.[levelId];
}

export function setLevelProgress(
  worldId: string,
  levelId: number,
  progress: LevelProgress,
): void {
  const all = loadQuestProgress();
  if (!all[worldId]) all[worldId] = {};
  const existing = all[worldId][levelId];
  // Лучшие звёзды/счёт сохраняются
  all[worldId][levelId] = {
    stars: Math.max(progress.stars, existing?.stars ?? 0),
    attempts: (existing?.attempts ?? 0) + 1,
    completedAt: progress.completedAt ?? existing?.completedAt,
    bestScore: Math.max(progress.bestScore ?? 0, existing?.bestScore ?? 0),
  };
  saveQuestProgress(all);
}

/** Какие уровни уже разблокированы в мире */
export function isLevelUnlocked(worldId: string, levelId: number): boolean {
  if (levelId === 1) return true;
  const all = loadQuestProgress();
  const prev = all[worldId]?.[levelId - 1];
  return !!prev && prev.stars > 0;
}
