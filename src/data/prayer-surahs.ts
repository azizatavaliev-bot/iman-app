export type PrayerKey = "fajr" | "dhuhr" | "asr" | "maghrib" | "isha";

export interface SurahRef {
  /** Surah number 1..114 */
  num: number;
  /** Reason / specific narration linking this surah to the prayer */
  reason?: string;
  /** Hadith reference (collection + number) */
  source?: string;
}

export interface PrayerInfo {
  key: PrayerKey;
  name: string;
  emoji: string;
  rakaats: number;
  /** Краткое объяснение характера чтения в этом намазе */
  hint: string;
  /** Какую часть мафассаля читал Пророк ﷺ */
  mafassal: "длинный" | "средний" | "короткий" | "смешанно";
  /** Что часто читал Пророк ﷺ — с источниками */
  sunnah: SurahRef[];
  /** Универсальные короткие, если выучил мало */
  fallback: number[];
  /** Особые сунны: что читал в пятницу / в особых случаях */
  special?: { occasion: string; surahs: number[]; source: string }[];
}

